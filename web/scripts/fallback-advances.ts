// Regenerates src/lib/fallback-advances.ts: per-letter advances of the letters
// TeX Gyre Heros lacks (Cyrillic, Armenian), measured in a real browser with
// the page's font stack. Run on macOS (the fallback fonts are the OS's):
//   pnpm exec vite-node scripts/fallback-advances.ts
// CHROMIUM_PATH picks a local Chromium instead of Playwright's download.
import { writeFileSync } from "node:fs";
import { chromium } from "playwright";

const RANGES: Record<string, [number, number]> = {
  cyrillic: [0x0400, 0x045f],
  armenian: [0x0531, 0x0587],
};

const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH });
const page = await browser.newPage();
const tables = await page.evaluate((ranges) => {
  const c = document.createElement("canvas").getContext("2d")!;
  c.font = '400 1000px "Helvetica Neue", Helvetica, Arial, sans-serif';
  const out: Record<string, string> = {};
  for (const [name, [a, z]] of Object.entries(ranges)) {
    const cells: string[] = [];
    for (let cp = a; cp <= z; cp++) {
      const ch = String.fromCodePoint(cp);
      if (/\p{L}/u.test(ch)) cells.push(`${ch}${Math.round(c.measureText(ch).width)}`);
    }
    out[name] = cells.join(" ");
  }
  return out;
}, RANGES);
await browser.close();

const body = Object.entries(tables)
  .map(([k, v]) => `  ${k}: "${v}",`)
  .join("\n");
writeFileSync(
  new URL("../src/lib/fallback-advances.ts", import.meta.url),
  `// GENERATED by scripts/fallback-advances.ts (run on macOS) — do not edit.
// Per-letter advances, in 1/1000 em, of the letters the bundled TeX Gyre Heros
// lacks, as macOS renders the page's font stack: Helvetica Neue's Cyrillic and
// the system Armenian fallback. lib/text-metrics.ts uses them to estimate
// ru/hy labels at build time; the client re-measures those labels anyway, so
// on other platforms a miss costs one correction, not a broken layout.

export const FALLBACK_ADVANCES: Record<string, string> = {
${body}
};
`,
);
console.log("wrote src/lib/fallback-advances.ts");
